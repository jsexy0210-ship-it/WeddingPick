/**
 * 원본 문서 보관 정책.
 *
 * 서비스정책서 4번의 미확정 항목이었다. **검증 완료 후 30일**로 정해졌다
 * (2026-08-28).
 *
 * "검증 완료"는 원본이 더 이상 필요하지 않게 된 시점이다. 셋 중 가장 나중이
 * 기준이 된다 — 업로드, 사용자 확인(A-07), 인증 심사 결론. 업로드가 바닥에
 * 있는 것은, 분석되지 않고 버려진 업로드가 영원히 남지 않게 하려는 것이다.
 *
 * 아직 결론이 나지 않은 인증 신청의 증빙이면 셈이 시작되지 않는다. 심사자가
 * 확인할 근거를 잃지 않게 하려는 것이고, 그 대가로 그동안 원본이 남는다.
 *
 * 실제 계산은 DB(`originals.document_retention_schedule`)가 한다. 확인과 심사가
 * 끝날 때마다 달라지는 값이라 저장하면 낡기 때문이다. 여기 있는 숫자는 그
 * 정책의 정본이고, `originals.retention_days()`와 같아야 한다 — 테스트가
 * 둘이 같은지 본다.
 */
export const RETENTION_POLICY = {
  /** 검증이 끝난 날로부터 며칠까지 원본을 보관하는가. */
  originalDays: 30,
} as const;

/**
 * 인증 심사 운영 기준.
 *
 * 심사가 열려 있는 동안 그 증빙 원본은 파기되지 않는다 — 지우면 심사자가 확인할
 * 근거를 잃기 때문이다(RETENTION_POLICY 참고). 그래서 심사가 밀리는 것은 심사만의
 * 문제가 아니라 **개인정보가 그만큼 오래 남는다는 뜻**이다.
 *
 * 며칠부터 밀린 것으로 볼지는 정해져야 알릴 수 있다. **7일로 정했다**(2026-08-28).
 *
 * 접수한 날부터 센다. 심사를 시작했다고(in_review) 시계를 되돌리지 않는다 —
 * 시작은 결론이 아니고, 신청한 사람이 기다리는 것은 결론이다.
 *
 * SQL 쪽 정본은 `structured.verification_backlog_days()`이고, 테스트가 둘이
 * 같은지 본다.
 */
export const VERIFICATION_POLICY = {
  /** 접수 후 며칠이 지나도록 결론이 나지 않으면 밀린 것으로 본다. */
  backlogDays: 7,
} as const;
