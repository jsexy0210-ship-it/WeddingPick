-- 원본 보관 기간 30일 확정 (2026-08-28).
--
-- 서비스정책서 4번의 미확정 항목이었다. 정해지기 전까지 ORIGINAL_RETENTION_DAYS가
-- 비어 있었고, 그동안 올라온 원본은 retention_until이 NULL이다. 그 문서들은
-- 파기 목록에도 알림에도 오르지 않는다 — 영원히 남는다.
--
-- 값을 정하는 것만으로는 그 문서들이 정리되지 않는다. 새로 올라오는 것에만
-- 적용되기 때문이다. 이미 있는 것에 일정을 소급해 붙인다.

UPDATE originals.raw_documents
   SET retention_until = uploaded_at + interval '30 days'
 WHERE retention_until IS NULL
   AND deleted_at IS NULL;

/*
 * 여기서 한 가지를 의도적으로 하지 않는다: **이미 지워진 문서는 건드리지 않는다.**
 * deleted_at이 있는 행은 파기 기록이다. 파기 기록에 뒤늦게 예정일을 적어 넣으면
 * "언제 지우기로 했었는지"가 사실과 달라진다.
 *
 * 그리고 소급 적용의 결과로, 30일보다 오래된 문서는 이 마이그레이션 직후 곧바로
 * 파기 대상이 된다. 그게 맞다 — 그 문서들은 진작 지워졌어야 했다. 운영자에게
 * 알림이 가고, 사람이 지운다.
