-- 최소 온보딩이 받는 지역. 통합정책 v3.10 §3.
--
-- 정책이 최초 필수입력을 **예식일과 지역** 둘로 줄였다. 이름은 빠졌다. 예식일은
-- 이미 있고, 지역이 없었다.
--
-- 지역으로 무엇을 하는가: 검색 기본 필터, TOP3와 웨딩픽 추천의 범위, 조건별
-- 통계의 첫 축이다. 이 값이 없으면 개인화는 전국 평균을 보여주는 일이 되는데,
-- 결혼 준비에서 전국 평균은 아무에게도 맞지 않는다.
--
-- **업체 지역 목록과 같은 문자열을 쓴다.** vendors.region이 자유 문자열이라
-- 외래키를 걸 수 없다. 대신 화면이 실제 업체가 있는 지역 목록에서만 고르게 한다 —
-- 업체가 한 곳도 없는 지역을 고르게 해두면 고른 순간부터 빈 화면이 된다.
--
-- NULL을 허용하는 이유: 이 컬럼이 생기기 전에 만들어진 웨딩이 있다. NULL은 "아직
-- 안 고름"이고, 화면은 그 상태에서 지역을 물어본다. 기본값을 깔면 서울에 사는
-- 사람과 서울을 고른 사람이 같은 값이 되어 구분이 사라진다.

ALTER TABLE structured.weddings
  ADD COLUMN region text
    CHECK (region IS NULL OR char_length(btrim(region)) > 0);

COMMENT ON COLUMN structured.weddings.region IS
  '준비 지역. NULL이면 아직 안 골랐다 — 기본값을 깔지 않는다. 업체 지역 목록과 같은 문자열.';
