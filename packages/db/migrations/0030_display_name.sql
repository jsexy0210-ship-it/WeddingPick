-- 부를 이름. 디자인 핸드오프 2번.
--
-- 0001은 users에 "계정 식별자만 둔다. 이름·연락처 같은 개인정보는 여기 두지 않는다"고
-- 적었다. 그 규칙을 여기서 한 칸 연다. 왜 열어도 되는지 적어둔다 — 규칙을 어길 때는
-- 왜 어기는지가 남아야 다음 사람이 같은 이유로만 어긴다.
--
--   1. **추출한 값이 아니라 적어준 값이다.** 추출규칙 10번이 막는 것은 문서에서
--      읽어낸 개인정보를 구조화 데이터에 복사하는 일이다. 이건 사용자가 뭐라고
--      불러달라고 직접 적은 말이다.
--   2. **5자다.** 본명을 받기에는 짧고 부르는 이름으로는 넉넉하다. 그게 의도다 —
--      우리가 원하는 것은 "지선님"이라고 부를 말이지 신원이 아니다.
--   3. **이것 하나뿐이다.** 연락처·생년월일·주소는 여전히 받지 않는다.
--
-- 이름을 안 받으면 홈이 "안녕하세요"라고만 말하게 되는데, 몇 달을 함께 쓰는 앱에서
-- 그건 남의 앱처럼 느껴진다.

ALTER TABLE structured.users
  ADD COLUMN display_name text
    CHECK (display_name IS NULL OR char_length(btrim(display_name)) BETWEEN 1 AND 5);

COMMENT ON COLUMN structured.users.display_name IS
  '부를 이름. 최대 5자. 사용자가 적어준 값이고 문서에서 추출한 값이 아니다 — users에 두는 유일한 개인정보다.';

COMMENT ON TABLE structured.users IS
  '계정 식별자와 부를 이름(최대 5자). 연락처·생년월일·주소 같은 것은 여기 두지 않는다.';

