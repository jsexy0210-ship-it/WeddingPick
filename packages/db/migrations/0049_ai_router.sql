-- 문서 분석에도 관문을 세운다. 화면데이터구조 스펙 7.3.
--
-- 스펙 7.3은 "모든 AI 요청 전에 DB조회/계산/규칙처리/캐시 가능 여부를 먼저 확인"을
-- 요구한다. 결제내역 읽기에는 그 관문이 있었지만(`proof-pipeline.ts`) **문서 분석은
-- 곧바로 모델을 불렀다.**
--
-- 더 나쁜 것은 부른 뒤에도 세지 않았다는 점이다. `document_extraction`이라는 기능
-- 이름은 처음부터 있었는데(0025) 그 이름으로 들어온 줄이 한 줄도 없었다. 그래서
-- **예산을 걸어도 문서 분석에는 걸리지 않았다** — `ai_budget_status`가 지출을 0으로
-- 보기 때문이다. 세지 않으면 한도는 장식이다.

-- ---------------------------------------------------------------------------
-- 누가 불렀는가
-- ---------------------------------------------------------------------------
--
-- 사용자별 일일 호출 제한(스펙 7.3)을 걸려면 호출에 사람이 붙어야 한다. 지금까지
-- `ai_usage`는 기능과 모델만 알고 있었다.
--
-- **탈퇴하면 사람만 지운다**(SET NULL). 비용 기록까지 사라지면 그 달의 합계가
-- 조용히 줄고, 예산이 실제보다 넉넉해 보인다 — 0045가 후기·제보에 쓴 규칙과 같다.

ALTER TABLE structured.ai_usage
  ADD COLUMN user_id uuid REFERENCES structured.users (id) ON DELETE SET NULL;

COMMENT ON COLUMN structured.ai_usage.user_id IS
  '부른 사람. NULL이면 탈퇴했거나 사람 없이 도는 호출이다 — 비용 기록은 남는다.';

/*
 * 하루치를 세는 색인. 제한을 거는 쪽이 매번 이 질문을 한다:
 * "이 사람이 오늘 몇 번 불렀는가."
 */
CREATE INDEX ai_usage_user_day_idx
  ON structured.ai_usage (user_id, requested_at DESC)
  WHERE user_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 부르지 못했다는 것도 결과다
-- ---------------------------------------------------------------------------
--
-- 예산이 바닥났거나 하루 한도를 넘겨 모델을 부르지 못했을 때, 지금은 적을 자리가
-- `internal`뿐이었다. 그건 서버가 고장났다는 뜻이고 화면은 "다시 시도해주세요"라고
-- 말한다 — **고장나지 않았는데 고장났다고 말하는 것이고, 다시 시도해도 같은 결과다.**
--
-- 결제내역 쪽은 규칙 파서가 있어 읽어주는 것만 멈추면 됐지만(스펙 7.3의 "AI가 죽어도
-- 핵심 서비스는 정상 동작해야 함"), 문서 분석에는 대신 읽어줄 규칙이 없다. 그러면
-- 할 수 있는 정직한 일은 못 했다고 말하는 것이다.

ALTER TYPE analysis_failure ADD VALUE 'unavailable';

COMMENT ON COLUMN structured.analyses.failure_reason IS
  '실패 이유. unavailable은 고장이 아니라 지금 부를 수 없다는 뜻이다 — 예산 또는 하루 한도.';
