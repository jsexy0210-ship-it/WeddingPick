-- 관리자 로그인을 신원 제공자 하나로 더한다.
--
-- 2026-09-10 사용자 요청 — 관리자 링크를 눌러도 로그인 화면이 안 나온다. 화면이
-- 없는 것이 아니라 **인증 경로 자체가 없었다**: admin/index가 확인 없이 내부 화면으로
-- 보내고, 서버가 403을 주지만 그 뜻을 말해 줄 자리가 없어 일반 오류로 보였다.
--
-- **사용자 로그인과 다른 길로 간다.** v3.25가 사용자 화면을 카카오 하나로 정했지만
-- 관리자는 예외다(사용자 결정) — 카카오 계정에 운영 권한을 매달면 그 계정을 잃었을 때
-- 권한을 회수할 방법이 카카오 쪽에 있게 된다.
--
-- **표를 새로 만들지 않고 있는 길을 쓴다.** identities → users → sessions는 이미
-- 세 가지를 하고 있다: 같은 사람이 다시 로그인하면 새 계정을 만들지 않고, 토큰
-- 원문을 저장하지 않고, 운영자에게 더 긴 세션을 준다. 관리자용으로 그것을 다시
-- 만들면 셋 중 하나를 빠뜨리게 된다.
--
-- 아이디와 비밀번호는 여기 없다. 서버가 아는 것은 환경변수 둘(`ADMIN_LOGIN_ID` ·
-- `ADMIN_PASSWORD_HASH`)이고, 뒤의 것은 소금과 해시만 담는다. 이 표에 남는 것은
-- 「그 아이디로 로그인한 사람이 누구인가」뿐이다.
--
-- **운영 권한은 여기서 켜지 않는다.** is_operator는 CLI로만 켠다 — 로그인 경로가
-- 권한까지 줄 수 있으면 그 한 곳이 뚫렸을 때 권한도 함께 넘어간다.

ALTER TYPE identity_provider ADD VALUE IF NOT EXISTS 'admin';

COMMENT ON TYPE identity_provider IS
  '신원 제공자. admin은 소셜이 아니라 아이디·비밀번호 로그인이다(0100) — 관리자 콘솔 전용.';
