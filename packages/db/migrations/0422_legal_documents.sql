-- 0422: 약관 · 방침 · 마케팅 동의를 «표»로 옮긴다
--
-- 2026-09-16 대표 지시 — 「개인정보처리방침 이용약관 마케팅 약관도 동일하게 내가
-- 수정가능하도록 하고」. 바로 앞 지시(관리자 FAQ처럼 코드에 박힌 것도 직접 고치게
-- 하라)와 같은 것을 법적 문서 셋에 적용한다.
--
-- **정본이 하나라는 규칙은 그대로다.** CLAUDE.md의 「약관과 개인정보처리방침의
-- 정본은 웹사이트다」(2026-09-11)가 막는 것은 «사본이 둘이 되는 것»이고, 그 위험은
-- 그대로다 — 2026-09-09에 앱과 방침이 어긋났고 낡은 쪽을 사용자가 봤다.
-- 뒤집히는 것은 「그 정본이 코드에 있다」뿐이다.
--
--     지금까지  apps/web/src/subpages.ts  →  웹이 그린다
--     이 판부터  이 표                     →  웹이 빌드할 때 읽어 그린다
--
-- 읽는 곳은 여전히 하나고, 앱은 지금처럼 웹으로 내보낸다. 앱에 사본을 만들지 않는다.
--
-- 표 자체(`terms_versions` · `terms_clauses`)는 0130에 이미 있다. 여기서 더하는 것은
-- 셋이다 — 시행일 · 표 모양 조문 · 지우면 안 되는 절 표시. 그리고 본문을 채운다.

-- ---------------------------------------------------------------------------
-- 1. 시행일
-- ---------------------------------------------------------------------------

/*
 * 저장한 날과 효력이 생기는 날은 다르다.
 *
 * 0130은 `published_at`(공개한 시각)만 두었다. 그것은 «우리가 언제 올렸는가»이지
 * «언제부터 이 글이 효력인가»가 아니다. 약관 변경은 시행일을 미리 알리고 그날부터
 * 적용하는 것이라(이용약관 제3조 · 방침 제13항) 두 날짜가 갈린다.
 *
 * 지금까지 이 값은 배포 환경변수 `LEGAL_TERMS_EFFECTIVE_ON`에 있었다
 * (`apps/web/src/legal-config.ts`). 판마다 다른 값인데 배포 전체에 하나뿐이라,
 * 옛 판이 언제부터 언제까지 효력이었는지를 말할 수 없었다. 판에 붙인다.
 */
ALTER TABLE structured.terms_versions
  ADD COLUMN effective_on date;

COMMENT ON COLUMN structured.terms_versions.effective_on IS
  '이 판이 효력을 갖기 시작하는 날. 공개한 시각(published_at)과 다르다 — 미리 알리고 나중에 시행한다.';

/*
 * 공개하려면 시행일이 있어야 한다.
 *
 * 초안에는 없어도 된다(아직 정하지 않았다). 공개는 「이 글이 언제부터 효력인지」를
 * 정하는 행위라, 그것을 비워둔 채 공개하면 사용자에게 시행일 없는 약관이 나간다.
 */
ALTER TABLE structured.terms_versions
  ADD CONSTRAINT published_version_states_its_effective_date
    CHECK (published_at IS NULL OR effective_on IS NOT NULL);

-- ---------------------------------------------------------------------------
-- 2. 표 모양 조문
-- ---------------------------------------------------------------------------

/*
 * 방침의 세 절은 «표»다 — 1항(목적·항목·보유기간) · 4항(수탁자) · 5항(국외 이전).
 * 줄글로 펴면 어느 수탁자가 어느 항목을 받는지가 뭉개진다.
 *
 * `body`(줄글)를 그대로 두고 옆에 둔다. 표가 있으면 표로 그리고, 없으면 `body`를
 * 줄바꿈으로 갈라 조항 목록으로 그린다 — 웹의 지금 그리는 법과 같다.
 */
ALTER TABLE structured.terms_clauses
  ADD COLUMN body_table jsonb;

COMMENT ON COLUMN structured.terms_clauses.body_table IS
  '표 모양 조문. {lead, cols:[{label}], rows:[[셀]]}. 없으면 body를 줄바꿈으로 갈라 그린다.';

/*
 * 모양이 맞는지 여기서 본다. 화면이 보내는 것을 믿고 담으면 웹 빌드가 터진다 —
 * 그때는 이미 고친 사람이 「저장됨」을 보고 화면을 닫은 뒤다.
 */
ALTER TABLE structured.terms_clauses
  ADD CONSTRAINT body_table_is_shaped_like_a_table
    CHECK (
      body_table IS NULL
      OR (
        jsonb_typeof(body_table -> 'cols') = 'array'
        AND jsonb_typeof(body_table -> 'rows') = 'array'
        AND jsonb_array_length(body_table -> 'cols') > 0
      )
    );

-- ---------------------------------------------------------------------------
-- 3. 지우면 안 되는 절
-- ---------------------------------------------------------------------------

/*
 * 편집을 열면 수탁자 목록과 국외 이전 절을 «실수로» 지울 수 있게 된다.
 *
 * CLAUDE.md — 「국외 이전만은 고지가 이전보다 먼저다. … 국외 이전 자체가 위법이
 * 아니라 고지 없이 이전하는 것이 위법이다」(개인정보보호법 제28조의8). 지금 방침에
 * 수탁자 다섯 곳과 국외 이전 다섯 건이 올라가 있고, 이 절이 비면 그 순간부터
 * 미고지 이전이 된다.
 *
 * **막지는 않는다.** 대표님이 고치실 수 있어야 한다. 이 표시가 하는 일은
 * 「무엇이 사라지는지 항목으로 보여준 뒤 한 번 더 확인」(v3.27 관리자 공통 규칙)을
 * 걸 자리를 표에 남기는 것이다 — 알고 지우는 것과 모르고 지우는 것을 가른다.
 */
ALTER TABLE structured.terms_clauses
  ADD COLUMN removal_warning text;

COMMENT ON COLUMN structured.terms_clauses.removal_warning IS
  '지우거나 비울 때 한 번 더 확인받을 절. 그 사유를 적는다. NULL이면 그냥 고칠 수 있다.';

-- ---------------------------------------------------------------------------
-- 4. 동의 기록이 판을 가리킨다
-- ---------------------------------------------------------------------------

/*
 * `user_consents`(0046)는 `terms_version text`로 판을 «이름»으로만 들고 있다.
 * 이름은 겹칠 수 있고 표와 이어져 있지 않아, 사용자가 동의한 글이 실제로 어느
 * 행이었는지를 댈 수 없다. 가리키게 한다.
 *
 * **기존 `terms_version` 칼럼을 지우지 않는다.** 지금까지 쌓인 동의 기록은 표에
 * 없는 판 이름(`draft-2026-09-01`)을 들고 있어서, 지우면 그 동의가 무엇에 대한
 * 동의였는지가 사라진다 — 이 작업이 막으려는 바로 그 일이다.
 *
 * nullable이다. 옛 기록은 채울 수 없고, 채운 척하면 없는 사실을 만드는 것이다.
 */
ALTER TABLE structured.user_consents
  ADD COLUMN terms_version_id uuid REFERENCES structured.terms_versions (id) ON DELETE RESTRICT;

COMMENT ON COLUMN structured.user_consents.terms_version_id IS
  '동의한 판. 옛 기록은 비어 있다 — 표가 생기기 전에 받은 동의라 가리킬 행이 없다.';

CREATE INDEX user_consents_version_idx
  ON structured.user_consents (terms_version_id)
  WHERE terms_version_id IS NOT NULL;

/*
 * 가리키는 판은 공개된 판이어야 한다.
 *
 * 초안에 동의를 받으면 그 뒤 초안이 고쳐지고, 동의한 글이 소리 없이 바뀐다.
 * 0130이 조문 변경을 막는 것과 같은 이유이고, 여기가 그 방어의 나머지 반쪽이다.
 */
CREATE FUNCTION structured.reject_consent_to_unpublished_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.terms_version_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM structured.terms_versions
    WHERE id = NEW.terms_version_id AND published_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION '공개되지 않은 판에는 동의를 받을 수 없다.';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER user_consents_point_at_published_versions
  BEFORE INSERT OR UPDATE ON structured.user_consents
  FOR EACH ROW EXECUTE FUNCTION structured.reject_consent_to_unpublished_version();

-- ---------------------------------------------------------------------------
-- 5. 이관한 판은 «사람이 공개한 것»이 아니다
-- ---------------------------------------------------------------------------

/*
 * 0130은 「공개했으면 공개한 사람이 있다」를 제약으로 걸었다
 * (`publication_names_the_person`). 사람이 관리자에서 누르는 것만 생각한 제약이다.
 *
 * **이관에는 누른 사람이 없다.** 이 판은 지금 이미 웹사이트에 나가 있는 글이고,
 * 마이그레이션이 그것을 표로 옮기는 것뿐이다. 여기에 아무 운영자 id나 적으면
 * **그 사람이 공개했다는 거짓이 감사 기록에 남는다** — 빈칸이 사실이다.
 *
 * 빈칸의 뜻을 «모른다»가 아니라 «이관»으로 못 박는다. 그래야 나중에 published_by가
 * 빠진 행을 보고 버그로 읽지 않는다.
 */
ALTER TABLE structured.terms_versions
  ADD COLUMN carried_over boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN structured.terms_versions.carried_over IS
  '마이그레이션이 웹사이트에서 옮겨 온 판. 사람이 공개한 것이 아니라 published_by가 빈다.';

ALTER TABLE structured.terms_versions
  DROP CONSTRAINT publication_names_the_person;

ALTER TABLE structured.terms_versions
  ADD CONSTRAINT publication_names_the_person_unless_carried_over
    CHECK (
      (published_at IS NULL AND published_by IS NULL)
      OR (published_at IS NOT NULL AND published_by IS NOT NULL)
      OR (published_at IS NOT NULL AND carried_over)
    );

/* 「사람이 공개했는데 이관 표시」는 모순이라 막는다. */
ALTER TABLE structured.terms_versions
  ADD CONSTRAINT carried_over_has_no_publisher
    CHECK (NOT carried_over OR published_by IS NULL);

