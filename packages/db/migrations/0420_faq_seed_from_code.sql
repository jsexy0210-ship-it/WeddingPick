--
-- 2026-09-16 대표 지시 — 「관리자 faq처럼 이미 코드로 등록되어 있는것도 내가 직접
-- 수정 삭제 가능하도록 하라고」. 2026-09-11 지시(「FAQ, 약관 방침, 링크 미리보기 등
-- 운영자가 직접 조작이 가능해야한다」)의 남은 절반이다.
--
-- **0230이 코드 항목을 잠가 둔 이유는 옳았지만 일곱 중 하나에만 해당했다.**
-- 0230 머리말: 「코드의 FAQ를 여기로 복사하지 않는다 — 답 안에 공개 기준 건수를
-- 계산해 넣는다(DISCLOSURE_THRESHOLDS). 그 문장을 글자로 복사해 두면 기준이 바뀌는
-- 날 표에 든 사본이 옛 수를 말하고, 문장이라서 아무도 고장으로 보지 않는다.」
-- 실제로 `${...}`를 쓰는 답은 `price-source` 하나였다. 나머지 여섯은 그냥 글이다.
-- **하나 때문에 일곱을 다 잠가 둔 상태였다.**
--
-- **그래서 그 하나는 자리표시자로 담는다.** 답에 `{{limited}}` · `{{detailed}}`라고
-- 적어 두고, 보여줄 때 `packages/domain/src/faq.ts`의 `fillFaqPlaceholders`가
-- DISCLOSURE_THRESHOLDS에서 값을 채운다. 운영자가 문장을 고쳐도 숫자는 코드에서
-- 온다 — 0230이 걱정한 「옛 수를 말하는 사본」이 생기지 않는다. 채울 수 없는 이름은
-- 저장할 때 400으로 막는다(`unknownFaqPlaceholders`).

-- 항목을 가리키는 이름. 화면의 주소(`/my/faq/<key>`)와 관련 질문·문의 유형 짝짓기가
-- 이 값으로 걸려 있어, 옮겨 온 일곱은 코드가 쓰던 키를 그대로 지닌다.
--
-- **운영자가 새로 등록한 항목은 비어 있다**(NULL). 그런 항목에는 관련 질문도 문의
-- 유형 짝도 없고, 화면은 id로 연다. 빈 문자열은 막는다 — 주소에 빈 키가 실리면
-- 조회가 엉뚱한 행을 집는다.
ALTER TABLE structured.faq_items
  ADD COLUMN key text UNIQUE CHECK (key <> '');

